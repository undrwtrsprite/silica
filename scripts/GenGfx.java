import java.io.IOException;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.nio.file.*;
import java.util.*;
import java.util.regex.*;
import java.util.stream.*;

/**
 * Generates dev.betavk.render.{Renderer,GLRenderer,Gfx} from the OpenGL members the sources actually use.
 * usage: java -cp <lwjgl jars> scripts/GenGfx.java <outDir> <srcRoot>...
 * Reflection over LWJGL 3 gives exact signatures, so the generated layer cannot drift from the real API.
 */
public class GenGfx {
    static final String[] CLASSES = {"GL11", "GL12", "GL13", "GL14", "GL15", "ARBOcclusionQuery", "ARBVertexBufferObject", "NVFogDistance"};

    record Sig(String name, Class<?> ret, Class<?>[] params, String owner) {
        String key() { return name + Arrays.toString(params); }
    }

    public static void main(String[] a) throws Exception {
        Path out = Paths.get(a[0]);
        Pattern use = Pattern.compile("\\b(" + String.join("|", CLASSES) + ")\\.([A-Za-z_0-9]+)");
        Map<String, Set<String>> used = new TreeMap<>();
        for (int i = 1; i < a.length; i++) {
            try (Stream<Path> s = Files.walk(Paths.get(a[i]))) {
                for (Path p : s.filter(x -> x.toString().endsWith(".java")).toList()) {
                    Matcher m = use.matcher(Files.readString(p));
                    while (m.find()) used.computeIfAbsent(m.group(1), k -> new TreeSet<>()).add(m.group(2));
                }
            }
        }
        used.computeIfAbsent("GL11", k -> new TreeSet<>()).addAll(List.of("glFrustum", "GL_RENDERER", "GL_VERSION"));   // used by default methods / harness
        Map<String, Sig> methods = new TreeMap<>();
        Map<String, Field> consts = new TreeMap<>();
        for (String cn : CLASSES) {
            Class<?> c = Class.forName("org.lwjgl.opengl." + cn);
            for (String name : used.getOrDefault(cn, Set.of())) {
                if (name.startsWith("gl")) {
                    for (Method m : c.getMethods()) {
                        if (!m.getName().equals(name) || !Modifier.isStatic(m.getModifiers())) continue;
                        if (m.getDeclaringClass() != c) continue;
                        if (Arrays.stream(m.getParameterTypes()).anyMatch(t -> t.getName().contains("MemoryStack"))) continue;
                        Sig s = new Sig(name, m.getReturnType(), m.getParameterTypes(), cn);
                        methods.putIfAbsent(s.key(), s);
                    }
                } else {
                    Field f = c.getField(name);
                    consts.putIfAbsent(name, f);
                }
            }
        }
        Path dir = out.resolve("dev/betavk/render");
        Files.createDirectories(dir);

        StringBuilder itf = new StringBuilder("package dev.betavk.render;\n\nimport java.nio.*;\n\n"
                + "/**\n * The renderer abstraction: the fixed-function vocabulary the b1.7.3 game uses (state, matrix stack, display lists,\n"
                + " * vertex arrays, textures). GENERATED by scripts/GenGfx.java from the members the game calls; do not edit.\n"
                + " * Backends: GLRenderer (OpenGL 2.1), and the Vulkan backend (Phase 2 step 6).\n */\npublic interface Renderer {\n"
                + "    String name();\n    boolean supportsOcclusionQueries();\n    boolean supportsVertexBufferObjects();\n    boolean supportsFogDistanceNV();\n\n"
                + "    default void gluPerspective(float fovy, float aspect, float zNear, float zFar) {\n"
                + "        double top = Math.tan(Math.toRadians(fovy) / 2.0) * zNear;\n        double right = top * aspect;\n"
                + "        glFrustum(-right, right, -top, top, zNear, zFar);\n    }\n\n"
                + "    default String gluErrorString(int error) {\n        return switch (error) {\n"
                + "            case 0x0500 -> \"Invalid enum\";\n            case 0x0501 -> \"Invalid value\";\n            case 0x0502 -> \"Invalid operation\";\n"
                + "            case 0x0503 -> \"Stack overflow\";\n            case 0x0504 -> \"Stack underflow\";\n            case 0x0505 -> \"Out of memory\";\n"
                + "            default -> \"Unknown error 0x\" + Integer.toHexString(error);\n        };\n    }\n\n");
        StringBuilder impl = new StringBuilder("package dev.betavk.render;\n\nimport java.nio.*;\nimport org.lwjgl.opengl.*;\n\n"
                + "/** OpenGL 2.1 backend. GENERATED by scripts/GenGfx.java; do not edit. */\npublic final class GLRenderer implements Renderer {\n"
                + "    private final boolean occlusion = GL.getCapabilities().GL_ARB_occlusion_query;\n"
                + "    private final boolean vbo = GL.getCapabilities().GL_ARB_vertex_buffer_object;\n"
                + "    private final boolean fogNv = GL.getCapabilities().GL_NV_fog_distance;\n\n"
                + "    @Override public String name() { return \"OpenGL\"; }\n"
                + "    @Override public boolean supportsOcclusionQueries() { return occlusion; }\n"
                + "    @Override public boolean supportsVertexBufferObjects() { return vbo; }\n"
                + "    @Override public boolean supportsFogDistanceNV() { return fogNv; }\n\n");
        StringBuilder gfx = new StringBuilder("package dev.betavk.render;\n\nimport java.nio.*;\n\n"
                + "/** Static facade over the active Renderer, plus the GL enum values the game uses. GENERATED by scripts/GenGfx.java. */\n"
                + "public final class Gfx {\n    private static Renderer r;\n\n    private Gfx() {\n    }\n\n"
                + "    public static void set(Renderer renderer) { r = renderer; }\n    public static Renderer get() { return r; }\n\n"
                + "    public static boolean supportsOcclusionQueries() { return r.supportsOcclusionQueries(); }\n"
                + "    public static boolean supportsVertexBufferObjects() { return r.supportsVertexBufferObjects(); }\n"
                + "    public static boolean supportsFogDistanceNV() { return r.supportsFogDistanceNV(); }\n"
                + "    public static void gluPerspective(float fovy, float aspect, float zNear, float zFar) { r.gluPerspective(fovy, aspect, zNear, zFar); }\n"
                + "    public static String gluErrorString(int error) { return r.gluErrorString(error); }\n\n");
        for (Field f : consts.values()) {
            Object v = f.get(null);
            String t = f.getType().getSimpleName();
            String lit = v instanceof Long ? v + "L" : v instanceof Float ? v + "F" : v instanceof Double ? v + "D" : v.toString();
            gfx.append("    public static final ").append(t).append(' ').append(f.getName()).append(" = ").append(lit).append(";\n");
        }
        gfx.append('\n');
        for (Sig s : methods.values()) {
            StringBuilder ps = new StringBuilder(), as = new StringBuilder();
            for (int i = 0; i < s.params.length; i++) {
                String t = s.params[i].getCanonicalName();
                ps.append(i > 0 ? ", " : "").append(t).append(" p").append(i);
                as.append(i > 0 ? ", " : "").append('p').append(i);
            }
            String ret = s.ret.getCanonicalName();
            String r = s.ret == void.class ? "" : "return ";
            itf.append("    ").append(ret).append(' ').append(s.name).append('(').append(ps).append(");\n");
            impl.append("    @Override public ").append(ret).append(' ').append(s.name).append('(').append(ps).append(") { ")
                    .append(r).append(s.owner).append('.').append(s.name).append('(').append(as).append("); }\n");
            gfx.append("    public static ").append(ret).append(' ').append(s.name).append('(').append(ps).append(") { ")
                    .append(r).append("r.").append(s.name).append('(').append(as).append("); }\n");
        }
        itf.append("}\n");
        impl.append("}\n");
        gfx.append("}\n");
        Files.writeString(dir.resolve("Renderer.java"), itf.toString());
        Files.writeString(dir.resolve("GLRenderer.java"), impl.toString());
        Files.writeString(dir.resolve("Gfx.java"), gfx.toString());
        System.out.println("generated " + methods.size() + " methods, " + consts.size() + " constants");
    }
}
